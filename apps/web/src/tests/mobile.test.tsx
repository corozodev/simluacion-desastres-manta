import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider, onlineManager } from '@tanstack/react-query';
import { afterEach, describe, expect, it, vi } from 'vitest';
import type { Incident, LabState } from '@corodev/contracts';
import MobileViewer from '../features/mobile/MobileViewer';
import type { WorldMapProps } from '../features/WorldMap';
import type { FloodMapProps } from '../features/flood/FloodMap';
import { api } from '../services/api';
import { graph, managedFlood, managedState, world as baseWorld } from './simulation-fixtures';

vi.mock('../features/WorldMap', () => ({ WorldMap: ({ world, selected, onSelect, lifecycle }: WorldMapProps) => <div aria-label="Mapa zombi de prueba" data-connected={String(lifecycle?.connected)}><p>Mapa en turno {world?.turn ?? 'vacío'}</p>{world?.survivors.map(agent => <button key={agent.id} onClick={() => onSelect?.(agent.id)}>Tocar {agent.id}</button>)}{selected && <p>Ruta seleccionada de {selected.id}</p>}</div> }));
vi.mock('../features/flood/FloodMap', () => ({ FloodMap: ({ scenario, citizen, incidents, onPickPosition, pickingCandidate, lifecycle }: FloodMapProps) => <div aria-label="Mapa inundación de prueba" data-connected={String(lifecycle?.connected)}><p>{citizen ? 'Mapa ciudadano sin tormenta' : `Tormenta en paso ${scenario?.simulation_step ?? 'vacío'}`}</p>{incidents?.map(incident => <p key={incident.incident_id}>{incident.description}</p>)}{pickingCandidate !== undefined && <button onClick={() => onPickPosition({ lat: -1, lng: -80 })}>Elegir calle</button>}</div> }));
const world = { ...baseWorld, survivors: [{ id: 'S-0001', current_node: graph.nodes[0]!.id, status: 'active' as const, target_shelter_id: graph.shelters[0]!.id, planned_route: [graph.nodes[0]!.id, graph.nodes[1]!.id] }] };
const now = '2026-10-27T13:00:00Z';
const incident: Incident = { schema_version: 1, incident_id: 'a'.repeat(32), incident_type: 'road_closed', latitude: -1, longitude: -80, description: 'Reporte ciudadano real', severity_reported: 'moderate', road_passability_reported: 'blocked', event_time: now, received_at: now, source_type: 'citizen', verification_status: 'pending', evidence_metadata: { attachment_count: 0, storage_status: 'not_supported' }, affected_edge_ids: [], graph_version: graph.version, snap_distance_m: 0, location_method: 'manual', location_precision_m: 20, expires_at: now, updated_at: now };
const flood: LabState = { run_id: 'flood-public-run', state: 'paused', mode: 'competition', graph_version: graph.version, config: { mode: 'competition', seed: 42, rainfall_profile: 'storm', hydraulic_model: 'rainfall_runoff_2d', rainfall_intensity: .8, simulation_duration: 150, evacuation_behavior: 'preventive', agents: 1, interval_ms: 2000, shelters: graph.shelters.map(shelter => ({ ...graph.nodes.find(node => node.id === shelter.node_id)!, id: shelter.id, label: shelter.id, capacity: shelter.capacity })) }, scenario: managedFlood().scenario_state!, shelters: graph.shelters, origins: [], timeline: [] };
function setup() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 }, mutations: { retry: false } } });
  vi.spyOn(api, 'graph').mockResolvedValue(graph);
  vi.spyOn(api, 'floodGraph').mockResolvedValue(graph);
  const published = vi.spyOn(api, 'publishedSimulation').mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'available', simulation: managedState(world) });
  const publicFlood = vi.spyOn(api, 'publishedFlood').mockResolvedValue(flood);
  vi.spyOn(api, 'incidents').mockResolvedValue({ incidents: [incident, { ...incident, incident_id: 'b'.repeat(32), source_type: 'synthetic', description: 'Reporte sintético oculto' }], total: 2, has_more: false, limit: 200, offset: 0 });
  vi.spyOn(api, 'referenceStatus').mockRejectedValue(new Error('Sin referencia disponible'));
  const createSimulation = vi.spyOn(api, 'createSimulation');
  const startFlood = vi.spyOn(api, 'startFlood');
  render(<QueryClientProvider client={client}><MobileViewer /></QueryClientProvider>);
  return { client, published, publicFlood, createSimulation, startFlood };
}
afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers(); onlineManager.setOnline(true); });

describe('visor ciudadano compartido', () => {
  it('se incorpora al turno actual, selecciona ruta y no ofrece ni llama controles de creación', async () => {
    const { createSimulation, startFlood } = setup();
    expect(await screen.findByText(`Mapa en turno ${world.turn}`)).toBeInTheDocument();
    expect(screen.getByText(`Turno ${world.turn}/150 · En ejecución`)).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: `Tocar ${world.survivors[0]!.id}` }));
    expect(await screen.findByText(`Ruta seleccionada de ${world.survivors[0]!.id}`)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: /Iniciar simulación|Iniciar tormenta|Pausar|Continuar|Cancelar simulación/ })).not.toBeInTheDocument();
    expect(createSimulation).not.toHaveBeenCalled(); expect(startFlood).not.toHaveBeenCalled();
    expect(sessionStorage.length + localStorage.length).toBe(0);
  });
  it('reinicia la selección al reemplazarse la referencia pública y no repite topología por turno', async () => {
    const { client, published } = setup();
    await screen.findByText(`Mapa en turno ${world.turn}`);
    fireEvent.click(screen.getByRole('button', { name: `Tocar ${world.survivors[0]!.id}` }));
    await screen.findByText(`Ruta seleccionada de ${world.survivors[0]!.id}`);
    const graphCalls = vi.mocked(api.graph).mock.calls.length;
    published.mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'available', simulation: managedState({ ...world, turn: 80 }, { tick: 80, simulation_id: 'new-public-run' }) });
    await client.invalidateQueries({ queryKey: ['published', 'zombie_outbreak'] });
    expect(await screen.findByText('Mapa en turno 80')).toBeInTheDocument();
    expect(screen.queryByText(`Ruta seleccionada de ${world.survivors[0]!.id}`)).not.toBeInTheDocument();
    expect(api.graph).toHaveBeenCalledTimes(graphCalls);
  });
  it('conserva el último snapshot con aviso al perder red y recupera el actual al reconectar', async () => {
    const { client, published, createSimulation } = setup();
    await screen.findByText(`Mapa en turno ${world.turn}`);
    published.mockRejectedValue(new Error('Sin red'));
    await client.invalidateQueries({ queryKey: ['published', 'zombie_outbreak'] });
    expect(await screen.findByText(/último estado puede estar desactualizado/)).toBeInTheDocument();
    expect(screen.getByText(`Mapa en turno ${world.turn}`)).toBeInTheDocument();
    published.mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'available', simulation: managedState({ ...world, turn: 84 }, { tick: 84 }) });
    act(() => onlineManager.setOnline(false)); act(() => onlineManager.setOnline(true));
    expect(await screen.findByText('Mapa en turno 84')).toBeInTheDocument();
    expect(createSimulation).not.toHaveBeenCalled();
  });
  it('avisa inmediatamente al quedar el navegador offline aunque TanStack pause sin error y recupera el estado actual', async () => {
    const { client, published, createSimulation, startFlood } = setup();
    await screen.findByText(`Mapa en turno ${world.turn}`);
    const online = vi.spyOn(navigator, 'onLine', 'get');
    online.mockReturnValue(false); fireEvent(window, new Event('offline'));
    expect(await screen.findByText(/Sin conexión; el último estado puede estar desactualizado/)).toBeInTheDocument();
    expect(screen.getByLabelText('Mapa zombi de prueba')).toHaveAttribute('data-connected', 'false');
    expect(screen.getByText(`Mapa en turno ${world.turn}`)).toBeInTheDocument();
    expect(client.getQueryState(['published', 'zombie_outbreak'])?.error).toBeNull();
    published.mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'available', simulation: managedState({ ...world, turn: 87 }, { tick: 87 }) });
    online.mockReturnValue(true); fireEvent(window, new Event('online'));
    expect(await screen.findByText('Mapa en turno 87')).toBeInTheDocument();
    expect(screen.queryByText(/Sin conexión; el último estado puede estar desactualizado/)).not.toBeInTheDocument();
    expect(screen.getByLabelText('Mapa zombi de prueba')).toHaveAttribute('data-connected', 'true');
    fireEvent.click(screen.getByRole('button', { name: 'Inundaciones' }));
    await screen.findByText('Reporte ciudadano real');
    online.mockReturnValue(false); fireEvent(window, new Event('offline'));
    const floodViewer = screen.getByRole('region', { name: 'Visor de inundaciones' });
    expect(within(floodViewer).getByText(/Sin conexión; el último estado puede estar desactualizado/)).toBeInTheDocument();
    expect(within(floodViewer).getByLabelText('Mapa inundación de prueba')).toHaveAttribute('data-connected', 'false');
    expect(within(floodViewer).getByText('Reporte ciudadano real')).toBeInTheDocument();
    online.mockReturnValue(true); fireEvent(window, new Event('online'));
    fireEvent.click(screen.getByRole('button', { name: 'Simulación experimental' }));
    await screen.findByText(`Tormenta en paso ${flood.scenario.simulation_step}`);
    online.mockReturnValue(false); fireEvent(window, new Event('offline'));
    expect(within(floodViewer).getByText(/Sin conexión; el último estado puede estar desactualizado/)).toBeInTheDocument();
    expect(within(floodViewer).getByLabelText('Mapa inundación de prueba')).toHaveAttribute('data-connected', 'false');
    expect(within(floodViewer).getByText(`Tormenta en paso ${flood.scenario.simulation_step}`)).toBeInTheDocument();
    expect(createSimulation).not.toHaveBeenCalled(); expect(startFlood).not.toHaveBeenCalled();
  });
  it('suspende observación al ocultarse y recupera el snapshot actual al volver', async () => {
    const { client, published } = setup();
    await screen.findByText(`Mapa en turno ${world.turn}`);
    const visibility = vi.spyOn(document, 'visibilityState', 'get');
    visibility.mockReturnValue('hidden'); fireEvent(document, new Event('visibilitychange'));
    const count = published.mock.calls.length;
    await client.invalidateQueries({ queryKey: ['published', 'zombie_outbreak'] });
    expect(published).toHaveBeenCalledTimes(count);
    published.mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'available', simulation: managedState({ ...world, turn: 90 }, { tick: 90 }) });
    visibility.mockReturnValue('visible'); fireEvent(document, new Event('visibilitychange'));
    expect(await screen.findByText('Mapa en turno 90')).toBeInTheDocument();
  });
  it('mantiene mapa sin ejecución y separa novedades ciudadanas de tormenta sintética', async () => {
    const { published, client, publicFlood, startFlood } = setup();
    published.mockResolvedValue({ scenario: 'zombie_outbreak', availability: 'none' });
    await client.invalidateQueries({ queryKey: ['published', 'zombie_outbreak'] });
    expect(await screen.findByText('Sin simulación activa')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Inundaciones' }));
    expect(await screen.findByText('Mapa ciudadano sin tormenta')).toBeInTheDocument();
    expect(await screen.findByText('Reporte ciudadano real')).toBeInTheDocument();
    expect(screen.queryByText('Reporte sintético oculto')).not.toBeInTheDocument();
    expect(publicFlood).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Simulación experimental' }));
    expect(await screen.findByText(`Tormenta en paso ${flood.scenario.simulation_step}`)).toBeInTheDocument();
    expect(screen.getByText('Simulación con datos sintéticos.')).toBeInTheDocument();
    expect(screen.queryByText('Reporte ciudadano real')).not.toBeInTheDocument();
    expect(startFlood).not.toHaveBeenCalled();
  });
  it('crea un reporte real revisado y reutiliza cuerpo/clave completos tras un fallo incierto', async () => {
    setup();
    vi.spyOn(api, 'incidentInfo').mockResolvedValue({ enabled: true, schema_version: 1, bounds: { min_latitude: -2, max_latitude: 0, min_longitude: -81, max_longitude: -79 }, max_description_length: 500, max_snap_distance_m: 500, verification_notice: 'Pendiente', photo_uploads_enabled: false });
    vi.spyOn(api, 'resolveIncident').mockResolvedValue({ matched: true, ambiguous: false, candidates: [{ edge_id: graph.edges[0]!.id, road_type: 'residential', distance_m: 1, from_node_id: graph.edges[0]!.from, to_node_id: graph.edges[0]!.to, latitude: -1, longitude: -80 }], message: 'Calle admisible', graph_version: graph.version, max_snap_distance_m: 500 });
    const create = vi.spyOn(api, 'createIncident').mockRejectedValueOnce(new Error('Respuesta perdida')).mockResolvedValue(incident);
    fireEvent.click(screen.getByRole('button', { name: 'Inundaciones' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Reportar novedad' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Elegir calle' }));
    const form = screen.getByRole('region', { name: 'Reportar novedad' });
    fireEvent.change(within(form).getByLabelText('Descripción breve'), { target: { value: 'Calle bloqueada por un árbol' } });
    await waitFor(() => expect(within(form).getByRole('button', { name: 'Revisar reporte' })).toBeEnabled());
    fireEvent.click(within(form).getByRole('button', { name: 'Revisar reporte' }));
    expect(create).not.toHaveBeenCalled();
    fireEvent.click(within(form).getByRole('button', { name: 'Enviar reporte' }));
    await screen.findByRole('alert');
    fireEvent.click(within(form).getByRole('button', { name: 'Enviar reporte' }));
    await waitFor(() => expect(create).toHaveBeenCalledTimes(2));
    expect(create.mock.calls[0]).toEqual(create.mock.calls[1]);
    expect(create.mock.calls[0]![0]).toMatchObject({ latitude: -1, longitude: -80, description: 'Calle bloqueada por un árbol', location_method: 'manual' });
    expect(await screen.findByRole('region', { name: 'Novedad seleccionada' })).toHaveTextContent('Pendiente de verificación');
  });
  it('exige elegir una calle real ante ubicación ambigua antes de revisar o enviar', async () => {
    setup();
    vi.spyOn(api, 'incidentInfo').mockResolvedValue({ enabled: true, schema_version: 1, bounds: { min_latitude: -2, max_latitude: 0, min_longitude: -81, max_longitude: -79 }, max_description_length: 500, max_snap_distance_m: 500, verification_notice: 'Pendiente', photo_uploads_enabled: false });
    vi.spyOn(api, 'resolveIncident').mockResolvedValue({ matched: false, ambiguous: true, candidates: [0, 1].map(index => ({ edge_id: graph.edges[index]!.id, road_type: 'residential', distance_m: index + 1, from_node_id: graph.edges[index]!.from, to_node_id: graph.edges[index]!.to, latitude: -1, longitude: -80 })), message: 'Selecciona una calle', graph_version: graph.version, max_snap_distance_m: 50 });
    const create = vi.spyOn(api, 'createIncident').mockResolvedValue(incident);
    fireEvent.click(screen.getByRole('button', { name: 'Inundaciones' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Reportar novedad' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Elegir calle' }));
    const form = screen.getByRole('region', { name: 'Reportar novedad' });
    fireEvent.change(within(form).getByLabelText('Descripción breve'), { target: { value: 'Obstáculo en una calle cercana' } });
    expect(within(form).getByRole('button', { name: 'Revisar reporte' })).toBeDisabled();
    fireEvent.click(await within(form).findByLabelText('Calle cercana 2 · a 2 m'));
    expect(within(form).getByRole('button', { name: 'Revisar reporte' })).toBeEnabled();
    expect(form).not.toHaveTextContent(graph.edges[1]!.id);
    fireEvent.click(within(form).getByRole('button', { name: 'Revisar reporte' }));
    fireEvent.click(within(form).getByRole('button', { name: 'Enviar reporte' }));
    await waitFor(() => expect(create).toHaveBeenCalledWith(expect.objectContaining({ edge_id_hint: graph.edges[1]!.id }), expect.any(String)));
  });

});
